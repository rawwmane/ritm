export function makeSeed() {
  let n = 0;
  return {
    projects: PROJECTS.map((p) => ({ ...p })),
    tasks: TASKS.map(([p, size, title, rep]) => ({
      id: 't' + ++n,
      p,
      size,
      title,
      rep: !!rep,
      count: 0,
      done: false,
      doneAt: null,
    })),
    rewards: REWARDS.map(([icon, title, cost], i) => ({ id: 'r' + (i + 1), icon, title, cost })),
    rules: { no: [...RULES.no], when: [...RULES.when], work: RULES.work },
  };
}
